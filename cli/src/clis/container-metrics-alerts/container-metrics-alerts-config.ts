import fs from 'fs';
import path from 'path';
import yaml from 'js-yaml';
import {
  loadIacToolboxYaml,
  resolveConfigPath,
} from 'src/loaders/yaml-loader.js';

interface IacToolboxYaml {
  [key: string]: unknown;
  container_metrics_alerts?: {
    enabled?: boolean;
    terraform_dest?: string;
    service_name?: string;
    [key: string]: unknown;
  };
}

/**
 * Load whether container metrics alerts are enabled from iac-toolbox.yml.
 * Returns undefined if not set.
 */
export function loadContainerMetricsAlertsEnabled(
  destination: string,
  filePath?: string
): boolean | undefined {
  const config = loadIacToolboxYaml(destination, filePath) as IacToolboxYaml;
  return config.container_metrics_alerts?.enabled;
}

